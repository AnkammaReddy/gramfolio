#!/usr/bin/env bash
# Idempotent repository bootstrap for GramFolio Cloud Agent / local dev.
#
# Database selection (in priority order):
#   1. An external DATABASE_URL from the environment (e.g. a Neon dev-branch
#      URL provided as a Cloud Agent secret). When present, the local Postgres
#      is NOT provisioned; dev-schema.sql is still applied to that database.
#   2. Otherwise, a self-contained local PostgreSQL is installed, started, and
#      seeded with scripts/dev-schema.sql.
#
# Then: installs Node dependencies (pinned pnpm, frozen lockfile) and writes
# .env.local with the chosen DATABASE_URL + a BETTER_AUTH_SECRET.
#
# Safe to run repeatedly. No secrets are required for the local-DB path.
set -euo pipefail

export COREPACK_ENABLE_DOWNLOAD_PROMPT=0
REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_DIR"

PG_VERSION=16
PG_CLUSTER=main
DB_USER=gramfolio
DB_PASS=gramfolio
DB_NAME=gramfolio
DB_HOST=127.0.0.1
DB_PORT=5432
LOCAL_DB_URL="postgresql://$DB_USER:$DB_PASS@$DB_HOST:$DB_PORT/$DB_NAME"

# An externally supplied DATABASE_URL (secret / env) wins over the local DB.
EXTERNAL_DB_URL="${DATABASE_URL:-}"

if [ -n "$EXTERNAL_DB_URL" ]; then
  echo "[install] External DATABASE_URL detected — using it and skipping local Postgres."
  DB_URL="$EXTERNAL_DB_URL"

  echo "[install] Testing connectivity to the external database (SELECT 1)..."
  # A real authenticated query is the reliable test: Neon's proxy accepts TCP
  # for any endpoint id, so a plain port check is not meaningful. Non-fatal —
  # surface the actual error so connectivity issues are easy to diagnose.
  if CONN_ERR="$(psql "$EXTERNAL_DB_URL" -tAc 'SELECT 1' 2>&1)"; then
    echo "[install] External database is reachable and authenticated."
  else
    echo "[install] WARNING: could not query the external database:"
    echo "[install]   $CONN_ERR"
    echo "[install]   Checklist: URL user/password/host/db correct; include sslmode=require (Neon);"
    echo "[install]   egress to the DB host allowed (allowlist *.neon.tech if egress is restricted)."
  fi

  echo "[install] Applying dev schema to external database..."
  DATABASE_URL="$EXTERNAL_DB_URL" node scripts/apply-dev-schema.mjs
else
  echo "[install] No external DATABASE_URL — provisioning local PostgreSQL."
  DB_URL="$LOCAL_DB_URL"

  echo "[install] Ensuring PostgreSQL is installed..."
  if ! command -v pg_ctlcluster >/dev/null 2>&1; then
    sudo apt-get update -y
    sudo DEBIAN_FRONTEND=noninteractive apt-get install -y postgresql postgresql-contrib
  fi

  echo "[install] Ensuring PostgreSQL cluster is running..."
  if ! pg_isready -h "$DB_HOST" -p "$DB_PORT" >/dev/null 2>&1; then
    sudo pg_ctlcluster "$PG_VERSION" "$PG_CLUSTER" start || true
  fi
  for _ in $(seq 1 30); do
    pg_isready -h "$DB_HOST" -p "$DB_PORT" >/dev/null 2>&1 && break
    sleep 1
  done

  echo "[install] Ensuring database role and database exist..."
  sudo -u postgres psql -tc "SELECT 1 FROM pg_roles WHERE rolname='$DB_USER'" | grep -q 1 \
    || sudo -u postgres psql -c "CREATE ROLE $DB_USER LOGIN PASSWORD '$DB_PASS';"
  sudo -u postgres psql -tc "SELECT 1 FROM pg_database WHERE datname='$DB_NAME'" | grep -q 1 \
    || sudo -u postgres psql -c "CREATE DATABASE $DB_NAME OWNER $DB_USER;"

  echo "[install] Applying dev schema..."
  PGPASSWORD="$DB_PASS" psql -h "$DB_HOST" -p "$DB_PORT" -U "$DB_USER" -d "$DB_NAME" \
    -v ON_ERROR_STOP=1 -f scripts/dev-schema.sql >/dev/null
  echo "[install] Schema applied."
fi

echo "[install] Installing Node dependencies..."
corepack pnpm install --frozen-lockfile

# Reuse an existing generated secret so sessions survive reruns; otherwise
# prefer an externally supplied BETTER_AUTH_SECRET, else generate one.
EXISTING_SECRET=""
EXISTING_MSG_KEY=""
if [ -f .env.local ]; then
  EXISTING_SECRET="$(grep -E '^BETTER_AUTH_SECRET=' .env.local | head -n1 | cut -d= -f2- || true)"
  EXISTING_MSG_KEY="$(grep -E '^MESSAGE_ENCRYPTION_KEY=' .env.local | head -n1 | cut -d= -f2- || true)"
fi
SECRET="${EXISTING_SECRET:-${BETTER_AUTH_SECRET:-$(openssl rand -base64 32)}}"
MSG_KEY="${EXISTING_MSG_KEY:-${MESSAGE_ENCRYPTION_KEY:-$(openssl rand -base64 32)}}"

echo "[install] Writing .env.local (DATABASE_URL$([ -n "$EXTERNAL_DB_URL" ] && echo ' = external/Neon' || echo ' = local Postgres'))..."
cat > .env.local <<EOF
# Local development env for GramFolio (git-ignored).
# Generated by .cursor/install.sh.
# To use a remote DB (e.g. Neon dev branch), set a DATABASE_URL secret in the
# Cloud Agent Secrets panel and re-run install — it takes precedence over local.
DATABASE_URL=$DB_URL
BETTER_AUTH_SECRET=$SECRET
MESSAGE_ENCRYPTION_KEY=$MSG_KEY
BETTER_AUTH_URL=http://localhost:3000
EOF

echo "[install] Done."
